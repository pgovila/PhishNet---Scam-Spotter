"""PhishNet report generation — plain-text summary for police reporting.

Produces a copyable plain-text report containing date, findings, score,
and optionally the original message text (only if the user opts in).
"""

from __future__ import annotations

from datetime import UTC, datetime

from phishnet.engine import AnalysisResult


def generate_report(
    result: AnalysisResult,
    *,
    include_message: bool = False,
    message_text: str = "",
    lang: str = "en",
) -> str:
    """Generate a plain-text report suitable for filing a complaint.

    Args:
        result: The AnalysisResult from the engine.
        include_message: Whether to include the original message text.
        message_text: The original message text (only used if include_message).
        lang: Language code ("en" or "hi").

    Returns:
        Plain-text report string.
    """
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    tier_map = {"high": "HIGH", "medium": "MEDIUM", "low": "LOW"}
    tier_label = tier_map.get(result.tier, result.tier.upper())

    lines: list[str] = [
        "=" * 50,
        "PHISHNET — SCAM ANALYSIS REPORT" if lang == "en" else "फ़िशनेट — स्कैम विश्लेषण रिपोर्ट",
        "=" * 50,
        f"Date: {now}",
        f"Risk Score: {result.score}/100",
        f"Risk Tier: {tier_label}",
        f"Scoring Mode: {result.mode}",
        "",
        "-" * 50,
        "FINDINGS:" if lang == "en" else "निष्कर्ष:",
        "-" * 50,
    ]

    for f in result.findings:
        status = "(protective — no points)" if f.protective else f"+{f.points} pts"
        lines.append(f"  [{f.category.upper()}] {f.label}: {status}")
        lines.append(f'    Matched: "{f.matched_text}"')
        if f.reason:
            lines.append(f"    Reason: {f.reason}")
        lines.append("")

    if result.act_now_applied:
        lines.append("  [BONUS] Act-now bonus applied: +15 pts")
        lines.append("")

    lines.append("-" * 50)
    lines.append("RECOMMENDED ACTIONS:" if lang == "en" else "सुझाई गई कार्रवाई:")
    lines.append("-" * 50)
    for step in result.next_steps:
        lines.append(f"  {step}")

    if include_message and message_text:
        lines.append("")
        lines.append("-" * 50)
        lines.append("ORIGINAL MESSAGE:" if lang == "en" else "मूल संदेश:")
        lines.append("-" * 50)
        lines.append(message_text)

    lines.extend(
        [
            "",
            "-" * 50,
            "Report generated by PhishNet (https://github.com/pgovila/PhishNet---Scam-Spotter)",
            "For cyber-crime complaints: https://cybercrime.gov.in | Helpline: 1930",
            "DoT Sanchar Saathi Chakshu: https://sancharsaathi.gov.in/sfc/Home/sfc-complaint.jsp",
            "=" * 50,
        ]
    )

    return "\n".join(lines)
